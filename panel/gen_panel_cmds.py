#!/usr/bin/env python3
"""Generate panel-huawei-dby-w09-cmds.h from the stock HarmonyOS device tree.

Reads the active panel node lcd_kit_debussy_110_20d_10p9_qcom from a dump of
the tablet's own device tree (dtc -I fs /proc/device-tree on HarmonyOS, or the
node cut out of it) and converts its Qualcomm DSI command arrays into tables
of {length, delay_ms, payload...}.

    gen_panel_cmds.py STOCK_PANEL.dts
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "panel-huawei-dby-w09-cmds.h"


def command_array(text: str, name: str) -> list[int]:
    match = re.search(r"\b" + re.escape(name) + r" = \[([0-9a-f ]+)\];", text)
    if not match:
        raise SystemExit(f"{name} not found")
    return [int(byte, 16) for byte in match.group(1).split()]


def parse(data: list[int]) -> list[tuple[int, list[int]]]:
    """Qualcomm format: type, last, vc, ack, wait_ms, len_hi, len_lo, payload."""
    commands, i = [], 0
    while i < len(data):
        kind, _, _, _, wait, len_hi, len_lo = data[i:i + 7]
        length = (len_hi << 8) | len_lo
        payload = data[i + 7:i + 7 + length]
        if kind not in (0x05, 0x15, 0x39) or len(payload) != length:
            raise SystemExit(f"unexpected command type {kind:#x} at byte {i}")
        commands.append((wait, payload))
        i += 7 + length
    return commands


def table(name: str, commands: list[tuple[int, list[int]]]) -> str:
    lines = [f"static const u8 {name}[] = {{"]
    for wait, payload in commands:
        body = ", ".join(f"0x{b:02x}" for b in payload)
        lines.append(f"\t{len(payload)}, {wait}, {body},")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("usage: gen_panel_cmds.py STOCK_PANEL.dts")
    text = Path(sys.argv[1]).read_text()
    on = parse(command_array(text, "qcom,mdss-dsi-on-command"))
    off = parse(command_array(text, "qcom,mdss-dsi-off-command"))
    OUT.write_text(
        "/* SPDX-License-Identifier: GPL-2.0-only */\n"
        "/* Generated by gen_panel_cmds.py from the stock DBY-W09 device tree\n"
        " * (lcd_kit_debussy_110_20d_10p9_qcom); entries are\n"
        " * {payload length, delay after it in ms, payload}. */\n\n"
        + table("dby_w09_on_cmds", on) + "\n\n"
        + table("dby_w09_off_cmds", off) + "\n")
    print(f"{OUT.name}: {len(on)} on commands, {len(off)} off commands", file=sys.stderr)


if __name__ == "__main__":
    main()
